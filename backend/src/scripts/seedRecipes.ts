async function seed(): Promise<void> {
  const uri = process.env.MONGODB_URI
  if (!uri) throw new Error("MONGODB_URI not set")

  await mongoose.connect(uri)
  console.log("✅ Connected to MongoDB")

  // Ensure AI user exists
  let aiUser = await User.findOne({ username: AI_USER.username })
  if (!aiUser) {
    aiUser = await User.create(AI_USER)
    console.log(`✅ Created AI user: ${AI_USER.name}`)
  } else {
    console.log(`⚠️  AI user already exists: ${AI_USER.username}`)
  }
  const userId = String(aiUser._id)

  let created = 0
  let skipped = 0

  for (const data of RECIPES) {
    const exists = await Recipe.findOne({ title: data.title, userId })
    if (exists) { skipped++; continue }
    const steps = data.instructions.join("\n")
    await Recipe.create({ ...data, steps, userId, isPersonal: false })
    console.log(`✅ ${data.title} [${data.category}]`)
    created++
  }

  console.log(`\nDone. Created: ${created}, Skipped: ${skipped}`)
  await mongoose.disconnect()
}

seed().catch(e => { console.error(e); process.exit(1) })
